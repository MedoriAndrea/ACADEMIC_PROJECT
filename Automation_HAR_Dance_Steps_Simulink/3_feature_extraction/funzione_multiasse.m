function [features, names] = funzione_multiasse(raw_matrix)

data = raw_matrix - mean(raw_matrix);

C = cov(data);
R = corr(data);

mag = sqrt(sum(raw_matrix.^2,2));

features = [ ...
    C(1,2), C(1,3), C(2,3), ...
    R(1,2), R(1,3), R(2,3), ...
    mean(mag), std(mag), rms(mag) ...
];

names = { ...
    "multi_cov_XY","multi_cov_XZ","multi_cov_YZ", ...
    "multi_corr_XY","multi_corr_XZ","multi_corr_YZ", ...
    "multi_mag_mean","multi_mag_std","multi_mag_rms" ...
};
end
