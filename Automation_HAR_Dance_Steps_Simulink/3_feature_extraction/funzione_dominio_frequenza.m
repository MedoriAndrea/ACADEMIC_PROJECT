function [features, names] = funzione_dominio_frequenza(raw_signal, Fs, N_win)

sig = double(raw_signal(:));
sig = sig - mean(sig);
L = length(sig);

target_len = 2^nextpow2(L);

w = hann(L);
sig_win = sig .* w;

Y = fft(sig_win, target_len);
P2 = abs(Y);
P1 = P2(1:target_len/2+1);
P1(2:end-1) = 2*P1(2:end-1);

f = Fs*(0:(target_len/2))/target_len;
f = f(:);

PowerSpec = P1.^2;
p_norm = PowerSpec/(sum(PowerSpec)+eps);

[max_mag, idx] = max(P1);
centroid = sum(f .* p_norm);
spread = sqrt(sum((f-centroid).^2 .* p_norm));

features = [ ...
    max_mag, ...
    f(idx), ...
    sum(PowerSpec), ...
    centroid, ...
    spread, ...
    sum(((f-centroid).^3).*p_norm)/(spread^3+eps), ...
    sum(((f-centroid).^4).*p_norm)/(spread^4+eps), ...
    angle(Y(idx)) ...
];

names = [ ...
    "freq_max_magnitude", ...
    "freq_dominant_frequency", ...
    "freq_total_power", ...
    "freq_spectral_centroid", ...
    "freq_bandwidth", ...
    "freq_spectral_skewness", ...
    "freq_spectral_kurtosis", ...
    "freq_phase_at_peak" ...
];
end
