function [features, names] = funzione_dominio_tempo(raw_signal)

signal = double(raw_signal(:));
abs_signal = abs(signal);

features = [ ...
    mean(signal), ...
    median(signal), ...
    var(signal), ...
    std(signal), ...
    max(signal), ...
    min(signal), ...
    (max(signal)-min(signal)), ...
    sum(signal.^2), ...
    rms(signal), ...
    max(abs_signal)/rms(signal) ...
];

names = { ...
    "time_mean", ...
    "time_median", ...
    "time_var", ...
    "time_std", ...
    "time_max", ...
    "time_min", ...
    "time_peak2peak", ...
    "time_energy", ...
    "time_rms", ...
    "time_crest_factor" ...
};
end
